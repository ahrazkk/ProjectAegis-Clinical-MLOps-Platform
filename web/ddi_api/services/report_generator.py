"""
Project Aegis - PDF Report Generator

Generates professional PDF reports for DDI analysis results using ReportLab.
"""

import io
import logging
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER, TA_LEFT, TA_RIGHT
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
    HRFlowable,
)

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Color helpers
# ---------------------------------------------------------------------------

def _risk_color(score: float) -> colors.Color:
    """Return an RGB color based on risk score thresholds."""
    if score < 0.3:
        return colors.HexColor('#22c55e')   # green
    elif score < 0.6:
        return colors.HexColor('#eab308')   # yellow
    elif score < 0.8:
        return colors.HexColor('#f97316')   # orange
    else:
        return colors.HexColor('#ef4444')   # red


def _risk_label(score: float) -> str:
    if score < 0.3:
        return 'LOW'
    elif score < 0.6:
        return 'MODERATE'
    elif score < 0.8:
        return 'HIGH'
    else:
        return 'CRITICAL'


# ---------------------------------------------------------------------------
# Shared styles
# ---------------------------------------------------------------------------

def _build_styles():
    ss = getSampleStyleSheet()

    title_style = ParagraphStyle(
        'AegisTitle',
        parent=ss['Title'],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor('#1e293b'),
        spaceAfter=4,
        alignment=TA_CENTER,
    )

    subtitle_style = ParagraphStyle(
        'AegisSubtitle',
        parent=ss['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#64748b'),
        alignment=TA_CENTER,
        spaceAfter=16,
    )

    section_style = ParagraphStyle(
        'AegisSection',
        parent=ss['Heading2'],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor('#1e293b'),
        spaceBefore=14,
        spaceAfter=6,
        borderPadding=(0, 0, 2, 0),
    )

    body_style = ParagraphStyle(
        'AegisBody',
        parent=ss['Normal'],
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#334155'),
        spaceAfter=6,
    )

    label_style = ParagraphStyle(
        'AegisLabel',
        parent=ss['Normal'],
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#64748b'),
    )

    disclaimer_style = ParagraphStyle(
        'AegisDisclaimer',
        parent=ss['Normal'],
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#94a3b8'),
        spaceBefore=24,
        alignment=TA_CENTER,
    )

    return {
        'title': title_style,
        'subtitle': subtitle_style,
        'section': section_style,
        'body': body_style,
        'label': label_style,
        'disclaimer': disclaimer_style,
    }


DISCLAIMER_TEXT = (
    "DISCLAIMER: This report is generated by an AI system and should not replace "
    "clinical judgment. Always consult qualified healthcare professionals before "
    "making clinical decisions based on these results."
)


# ---------------------------------------------------------------------------
# Shared elements
# ---------------------------------------------------------------------------

def _header_elements(styles, subtitle_text: str = ''):
    elements = []
    elements.append(Paragraph('Project Aegis', styles['title']))
    elements.append(Paragraph('Drug Interaction Report', styles['subtitle']))
    if subtitle_text:
        elements.append(Paragraph(subtitle_text, styles['subtitle']))
    timestamp = datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')
    elements.append(Paragraph(f'Generated: {timestamp}', styles['label']))
    elements.append(Spacer(1, 6))
    elements.append(HRFlowable(width='100%', thickness=1, color=colors.HexColor('#cbd5e1')))
    elements.append(Spacer(1, 12))
    return elements


def _disclaimer_elements(styles):
    elements = []
    elements.append(HRFlowable(width='100%', thickness=0.5, color=colors.HexColor('#e2e8f0')))
    elements.append(Paragraph(DISCLAIMER_TEXT, styles['disclaimer']))
    return elements


def _kv_table(pairs, styles):
    """Build a two-column key-value table from a list of (label, value) tuples."""
    data = []
    for label, value in pairs:
        data.append([
            Paragraph(f'<b>{label}</b>', styles['label']),
            Paragraph(str(value), styles['body']),
        ])
    if not data:
        return Spacer(1, 0)

    t = Table(data, colWidths=[2.0 * inch, 4.5 * inch])
    t.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (0, -1), 0),
        ('LINEBELOW', (0, 0), (-1, -2), 0.5, colors.HexColor('#f1f5f9')),
    ]))
    return t


